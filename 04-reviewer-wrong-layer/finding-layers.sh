#!/usr/bin/env bash
# Проверка находки ревьюера на нужном слое. Нужны git и bash; для режима gen — ваша команда генерации.
#
#   bash finding-layers.sh file <путь> <от>,<до> <базовая-ревизия> [ревизия-после, по умолчанию HEAD]
#       Печатает строки <от>..<до> файла на двух ревизиях с НАСТОЯЩИМИ номерами строк,
#       затем — сколько раз строка <искомое> из переменной NEEDLE встречается в файле на каждой
#       ревизии и в самом диффе между ними. Отвечает на «эта строка появилась/пропала в правке?».
#   bash finding-layers.sh gen <путь-исходника> '<подстрока>' '<команда генерации>'
#       Считает ВХОЖДЕНИЯ буквальной подстроки в исходнике и в stdout команды генерации.
#       Отвечает на «в исходнике N вхождений, значит проверка не пройдёт».
# Любая ошибка (нет ревизии, нет файла, команда генерации упала) — сообщение и код 1, без чисел.
set -uo pipefail
die() { echo "ошибка: $*" >&2; exit 1; }
count() { { grep -oF -- "$1" || [ $? -eq 1 ]; } | wc -l; }   # grep: 1 = нет совпадений (это ноль), 2 = ошибка   # вхождения буквальной подстроки, не строки с совпадением
case "${1:-}" in
  file)
    [ $# -ge 4 ] || die "нужно: file <путь> <от>,<до> <база> [после]"
    f=$2; r=$3; base=$4; head=${5:-HEAD}; from=${r%,*}; to=${r#*,}
    b1=$(git show "$base:$f" 2>/dev/null) || die "нет файла $f на ревизии $base"
    b2=$(git show "$head:$f" 2>/dev/null) || die "нет файла $f на ревизии $head"
    if [ -n "${NEEDLE:-}" ]; then d=$(git diff "$base" "$head" -- "$f" 2>/dev/null) || die "git diff $base $head не выполнился"; fi
    for rev in "$base" "$head"; do
      if [ "$rev" = "$base" ]; then body=$b1; else body=$b2; fi
      echo "== $f, строки $from–$to, ревизия $rev"
      printf '%s\n' "$body" | awk -v a="$from" -v b="$to" 'NR>=a && NR<=b {printf "%6d  %s\n", NR, $0}'
      if [ -n "${NEEDLE:-}" ]; then echo "   вхождений «$NEEDLE» в файле: $(printf '%s\n' "$body" | count "$NEEDLE")"; fi
    done
    if [ -n "${NEEDLE:-}" ]; then
      echo "   вхождений «$NEEDLE» в диффе $base..$head: $(printf '%s\n' "$d" | count "$NEEDLE")"
    fi ;;
  gen)
    [ $# -eq 4 ] || die "нужно: gen <исходник> '<подстрока>' '<команда>'"
    src=$2; needle=$3; gen=$4
    [ -f "$src" ] && [ -r "$src" ] || die "исходник $src — не читаемый обычный файл"
    text=$(cat -- "$src") || die "не удалось прочитать $src"
    out=$(bash -c "$gen") || die "команда генерации завершилась с ошибкой"
    n1=$(printf '%s\n' "$text" | count "$needle") || die "подсчёт в исходнике не выполнился"
    n2=$(printf '%s\n' "$out" | count "$needle") || die "подсчёт в выводе генератора не выполнился"
    echo "вхождений «$needle» в исходнике $src: $n1"
    echo "вхождений «$needle» в выводе генератора: $n2" ;;
  *) sed -n '2,13p' "$0"; exit 2 ;;
esac
